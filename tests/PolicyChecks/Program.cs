using NegotiableAR;

int passed = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception("FAIL: " + name); passed++; Console.WriteLine("PASS: " + name); }
NegotiationPolicy New() => new(new AgentConfig());
Observation Seen(string hint = "Would you like to compare two arrangements?") => new() { confidence = 0.9f, suggestedHint = hint };
ActivityEvidence Paused() => new() { HandsReliable = true, LookingAtWorkspace = true, LastMovementTime = 0 };
var p = New();
Check(p.Tick(20, Paused()).Action == AgentAction.Silent, "No offer without perception");
p.Observe(Seen(), 20);
Check(p.Tick(20, Paused()).Action == AgentAction.Offer, "Ambiguous pause produces an offer, not a hint");
Check(p.Tick(25, Paused()).Action == AgentAction.Silent && p.OfferPending, "Silence does not accept an offer");
Check(p.Tick(31, Paused()).Action == AgentAction.Silent && !p.OfferPending && p.IgnoredOffers == 1, "Unanswered offer expires");
Check(p.CooldownSeconds > 25 && p.Mode == AssistanceMode.Negotiated, "Ignored offer backs off without inventing permanent intent");
Check(p.Signal(UserSignal.Accept, 32).Action == AgentAction.Silent, "Expired offer cannot be accepted");
p = New(); p.Observe(Seen(), 20); p.Tick(20, Paused());
Check(p.Signal(UserSignal.Accept, 31).Action == AgentAction.Silent, "Acceptance checks expiry before next tick");
p = New(); p.Observe(Seen(), 20); p.Tick(20, Paused());
Check(p.Signal(UserSignal.Accept, 21).Action == AgentAction.Hint, "Explicit acceptance delivers a grounded hint");
p = New(); p.Observe(Seen(), 20); var active = Paused(); active.HandsMoving = true;
Check(p.Tick(20, active).Action == AgentAction.Silent, "Do not interrupt active manipulation");
active = Paused(); active.HandsReliable = false;
Check(p.Tick(20, active).Action == AgentAction.Silent, "Lost hand tracking is not inaction");
active = Paused(); active.LookingAtWorkspace = false;
Check(p.Tick(20, active).Action == AgentAction.Silent, "Do not offer when looking away");
Check(p.Tick(40, Paused()).Action == AgentAction.Silent, "Stale visual context cannot trigger intervention");
p = New(); var low = Seen(); low.confidence = 0.1f; p.Observe(low, 20);
Check(p.Tick(20, Paused()).Action == AgentAction.Silent, "Low visual confidence suppresses unsolicited offers");
p = New(); p.Observe(Seen(), 20); p.Tick(20, Paused()); p.Signal(UserSignal.Decline, 21);
Check(p.Tick(22, Paused()).Action == AgentAction.Silent && !p.OfferPending, "Decline prevents repeated immediate offers");
p.Signal(UserSignal.Quiet, 22); p.Observe(Seen(), 200);
Check(p.Tick(200, Paused()).Action == AgentAction.Silent, "Quiet persists across fresh observations");
Check(p.Signal(UserSignal.RequestHelp, 201).Action == AgentAction.Hint && p.Mode == AssistanceMode.Quiet, "Direct request works in quiet mode without overriding preference");
p = New();
Check(p.Signal(UserSignal.RequestHelp, 200).What == "W08", "Help without fresh vision asks about intent");
p.Mode = AssistanceMode.OnRequest; p.Observe(Seen(), 200);
Check(p.Tick(200, Paused()).Action == AgentAction.Silent, "On-request experimental condition suppresses proactive offers");
for (int i = 0; i < 30; i++) p.Signal(UserSignal.LessHelp, 200 + i);
Check(p.CooldownSeconds <= 120, "Adaptive cooldown is bounded");
p = New(); p.Observe(Seen(), 20); p.Tick(20, Paused());
Check(p.Signal(UserSignal.Accept, 29).What == "W08", "Accepted offer with stale vision asks a clarification");
var pointer = new PointerGesture();
Check(pointer.Update(1, true) == PointerPhase.Pressed, "Trigger press starts exactly one pointer action");
Check(pointer.Update(1, true) == PointerPhase.Held, "Holding a drag cannot repeatedly click buttons");
Check(pointer.Update(1, false) == PointerPhase.Released, "Release ends dragging");
Check(pointer.Update(1, true) == PointerPhase.Pressed, "A new physical press can start a new action");
Check(pointer.Update(0, false) == PointerPhase.Released, "Tracking loss releases the drag");
Check(pointer.Update(0, false) == PointerPhase.None && pointer.Update(1, true) == PointerPhase.None, "Reacquiring a still-pinched hand cannot click or accept help");
pointer.Update(1, false);
Check(pointer.Update(1, true) == PointerPhase.Pressed, "Recovered pointer works after a deliberate release");
Check(pointer.Update(2, true) == PointerPhase.Released && pointer.Update(2, true) == PointerPhase.None, "Changing hands while held does not create another click");
Console.WriteLine($"{passed} policy and pointer checks passed.");
